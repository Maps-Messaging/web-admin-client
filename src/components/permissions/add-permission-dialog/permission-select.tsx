import { usePermissionList } from "@/components/permissions/hooks";
import {
  Combobox,
  ComboboxChip,
  ComboboxChips,
  ComboboxChipsInput,
  ComboboxContent,
  ComboboxEmpty,
  ComboboxItem,
  ComboboxList,
  ComboboxValue,
  useComboboxAnchor,
} from "@/components/ui/combobox";
import type { FunctionComponent } from "react";

interface PermissionSelectProps {
  value: string[];
  handleChange: (value: string[]) => void;
}

export const PermissionSelect: FunctionComponent<PermissionSelectProps> = ({
  value,
  handleChange,
}) => {
  const { data } = usePermissionList();

  const anchor = useComboboxAnchor();

  return (
    <Combobox
      multiple
      autoHighlight
      items={data?.permissions ?? []}
      value={value}
      onValueChange={handleChange}
    >
      <ComboboxChips ref={anchor} className="w-full max-w-xs">
        <ComboboxValue>
          {(values) => (
            <>
              {values.map((value: string) => (
                <ComboboxChip key={value}>{value}</ComboboxChip>
              ))}
              <ComboboxChipsInput />
            </>
          )}
        </ComboboxValue>
      </ComboboxChips>
      <ComboboxContent anchor={anchor}>
        <ComboboxEmpty>No items found.</ComboboxEmpty>
        <ComboboxList>
          {(item) => (
            <ComboboxItem key={item.name} value={item.name}>
              {item.name}
            </ComboboxItem>
          )}
        </ComboboxList>
      </ComboboxContent>
    </Combobox>
  );
};
